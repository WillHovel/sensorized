#pragma once
#include <Arduino.h>

// ---------------------------------------------------------------------------
// Flex sensor wiring
// ---------------------------------------------------------------------------
// Each flex sensor forms a voltage divider with a fixed 10.0k ohm resistor
// (per the sensor's own datasheet, which pairs it with a 10k fixed resistor
// - the sensor sits at ~10k ohm itself at rest) between 3V3 and GND. The
// divider midpoint feeds one of the ADC pins below.
//
// GPIO1-GPIO5 are used because they are ADC1 channels (ADC1 stays usable
// even if you later add Wi-Fi/BLE, unlike ADC2) and are not strapping pins
// on the ESP32-S3, so they're safe to use freely.
static const int FLEX_PINS[] = {1, 2, 3, 4, 5}; // GPIO1..GPIO5 = ADC1_CH0..CH4
#define NUM_SENSORS (sizeof(FLEX_PINS) / sizeof(FLEX_PINS[0]))

// Raw ADC samples averaged per reading, to cut down noise.
#define ADC_OVERSAMPLE 8

